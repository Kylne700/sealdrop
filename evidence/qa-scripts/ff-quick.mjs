import { serve, launch, watch, PROJECT } from '/tmp/qa/lib.mjs'
const problems = []
const srv = await serve(PROJECT + '/dist')
const t0 = Date.now()
const browser = await launch('firefox')
console.log('firefox launched:', await browser.version(), `in ${Date.now() - t0} ms`)
const page = await browser.newPage()
watch(page, 'ff', problems)
await page.goto(srv.url)
await page.waitForSelector('h1')
console.log('home h1:', await page.$eval('h1', (e) => e.textContent), '| title:', await page.title())
await page.click('[data-testid=open-newsroom]')
await page.waitForSelector('[data-testid=create-newsroom]')
console.log('newsroom onboarding reached; hash =', await page.evaluate(() => location.hash))
await page.goto(srv.url + '#/send/0x123/abc')
await page.waitForSelector('[data-testid=route-notice]')
console.log('malformed link notice:', (await page.$eval('[data-testid=route-notice]', (e) => e.textContent)).slice(0, 60))
console.log('problems:', problems.length ? problems.join(' | ') : 0)
await browser.close(); await srv.close()
